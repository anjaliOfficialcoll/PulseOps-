export const generateHistoricalResults = (monitorId: string, count: number = 30): MonitoringResult[] => {
  const results: MonitoringResult[] = [];
  const now = Date.now();
  for (let i = count - 1; i >= 0; i--) {
    const timestamp = new Date(now - i * 60 * 1000).toISOString();
    let isSuccess = true;
    let statusCode = 200;
    let responseTimeMs = Math.floor(35 + Math.random() * 40);

    if (monitorId === 'mon-104') {
      if (i < 8) {
        isSuccess = false;
        statusCode = 504;
        responseTimeMs = 10000;
      } else {
        responseTimeMs = Math.floor(400 + Math.random() * 300);
      }
    } else if (monitorId === 'mon-103') {
      responseTimeMs = Math.floor(750 + Math.random() * 1100);
      if (Math.random() > 0.85) {
        isSuccess = false;
        statusCode = 503;
      }
    }

    results.push({
      id: `res-${monitorId}-${i}`,
      monitorId,
      statusCode,
      responseTimeMs,
      isSuccess,
      errorMessage: isSuccess ? undefined : (statusCode === 504 ? 'Gateway Timeout (10000ms reached)' : 'Service Unavailable'),
      checkedAt: timestamp,
      dnsLookupMs: Math.floor(2 + Math.random() * 8),
      tlsHandshakeMs: Math.floor(8 + Math.random() * 15),
    });
  }
  return results;
};

